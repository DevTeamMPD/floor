create or replace function public.create_floor_ncr(
  p_job_no text, p_title text, p_type text, p_product_sku text default null,
  p_quantity numeric default null, p_description text default null,
  p_estimated_value_thb numeric default null, p_created_by text default null,
  p_severity text default 'medium'
) returns uuid language plpgsql security definer set search_path=public as $$
declare v_actor public.floor_staff_profiles%rowtype; v_id uuid; v_due timestamptz;
begin
  select * into v_actor from public.floor_staff_profiles where id=(select auth.uid()) and is_active
    and role in ('admin','head_technician','warehouse','cs');
  if v_actor.id is null then raise exception 'NCR permission required'; end if;
  if nullif(btrim(coalesce(p_job_no,'')),'') is null or not exists(select 1 from public.install_jobs where job_no=p_job_no) then raise exception 'valid job number is required'; end if;
  if nullif(btrim(coalesce(p_title,'')),'') is null then raise exception 'NCR title is required'; end if;
  if p_severity not in ('critical','high','medium','low') then raise exception 'invalid NCR severity'; end if;
  v_due := now() + case p_severity when 'critical' then interval '4 hours' when 'high' then interval '24 hours' when 'medium' then interval '7 days' else interval '14 days' end;
  insert into public.ncr_reports(job_no,title,type,status,product_sku,quantity,description,estimated_value_thb,created_by,severity,due_at,owner_staff_id,created_at,updated_at)
  values(p_job_no,left(btrim(p_title),300),p_type,'open',nullif(btrim(coalesce(p_product_sku,'')),''),p_quantity,nullif(left(btrim(coalesce(p_description,'')),3000),''),p_estimated_value_thb,coalesce(nullif(btrim(coalesce(p_created_by,'')),''),v_actor.full_name),p_severity,v_due,v_actor.id,now(),now()) returning id into v_id;
  insert into public.floor_ncr_events(ncr_id,event_type,to_status,actor_id,detail) values(v_id,'created','open',v_actor.id,jsonb_build_object('severity',p_severity,'dueAt',v_due));
  return v_id;
end $$;
revoke all on function public.create_floor_ncr(text,text,text,text,numeric,text,numeric,text,text) from public,anon,authenticated;
grant execute on function public.create_floor_ncr(text,text,text,text,numeric,text,numeric,text,text) to authenticated;

create or replace function public.advance_floor_ncr(p_ncr_id uuid, p_next_status text)
returns boolean language plpgsql security definer set search_path=public as $$
declare v_actor public.floor_staff_profiles%rowtype; v_ncr public.ncr_reports%rowtype; v_allowed boolean;
begin
  select * into v_actor from public.floor_staff_profiles where id=(select auth.uid()) and is_active
    and role in ('admin','head_technician','warehouse','cs');
  if v_actor.id is null then raise exception 'NCR permission required'; end if;
  select * into v_ncr from public.ncr_reports where id=p_ncr_id for update;
  if v_ncr.id is null then raise exception 'NCR not found'; end if;
  v_allowed := (v_ncr.status='open' and p_next_status='investigating') or
    (v_ncr.status='investigating' and p_next_status='corrective_action') or
    (v_ncr.status='corrective_action' and p_next_status='verified') or
    (v_ncr.status='verified' and p_next_status='closed');
  if not v_allowed then raise exception 'invalid NCR status transition'; end if;
  update public.ncr_reports set status=p_next_status,updated_at=now(),
    verified_at=case when p_next_status='verified' then now() else verified_at end,
    verified_by=case when p_next_status='verified' then v_actor.id else verified_by end,
    closed_at=case when p_next_status='closed' then now() else closed_at end where id=p_ncr_id;
  insert into public.floor_ncr_events(ncr_id,event_type,from_status,to_status,actor_id) values(p_ncr_id,'status_changed',v_ncr.status,p_next_status,v_actor.id);
  return true;
end $$;
revoke all on function public.advance_floor_ncr(uuid,text) from public,anon,authenticated;
grant execute on function public.advance_floor_ncr(uuid,text) to authenticated;

create or replace function public.approve_floor_close_exception(p_job_no text,p_reason text)
returns uuid language plpgsql security definer set search_path=public as $$
declare v_actor public.floor_staff_profiles%rowtype; v_id uuid; v_missing jsonb;
begin
  select * into v_actor from public.floor_staff_profiles where id=(select auth.uid()) and is_active
    and lower(email)=lower('Supakrit.k@mpdgroup.co');
  if v_actor.id is null then raise exception 'close exception approver permission required'; end if;
  select to_jsonb(array_remove(array[
    case when not exists(select 1 from public.floor_work_order_events e join public.floor_work_orders w on w.id=e.work_order_id where w.job_no=p_job_no and e.event_type='customer_signed') then 'customer_signature' end,
    case when not exists(select 1 from public.floor_remnant_reports r where r.job_no=p_job_no and r.status='accepted') then 'accepted_remnant_report' end,
    case when not exists(select 1 from public.job_evaluations j where j.job_no=p_job_no and j.satisfaction_score is not null) then 'csat' end
  ]::text[],null)) into v_missing;
  insert into public.floor_close_exceptions(job_no,reason,missing_requirements,approved_by) values(p_job_no,btrim(p_reason),v_missing,v_actor.id) returning id into v_id;
  return v_id;
end $$;
revoke all on function public.approve_floor_close_exception(text,text) from public,anon,authenticated;
grant execute on function public.approve_floor_close_exception(text,text) to authenticated;

-- Track CSAT due three days after customer signature without blocking signature flow.
create or replace function public.track_floor_csat_and_closing_documents()
returns trigger language plpgsql security definer set search_path=public as $$
declare v_job_no text;
begin
  select job_no into v_job_no from public.floor_work_orders where id=new.work_order_id;
  if v_job_no is null then return new; end if;
  begin
    if new.event_type='customer_signed' then
      insert into public.floor_csat_followups(job_no,work_order_id,customer_signed_at,due_at)
      values(v_job_no,new.work_order_id,new.occurred_at,new.occurred_at+interval '3 days')
      on conflict(job_no) do update set work_order_id=excluded.work_order_id,customer_signed_at=excluded.customer_signed_at,due_at=excluded.due_at,completed_at=null,evaluation_id=null,updated_at=now();
      perform public.enqueue_floor_document_job(v_job_no,'customer_acceptance','04-installation','quality_record','customer_signed',new.id::text,new.occurred_at);
    elsif new.event_type='remnants_submitted' then
      perform public.enqueue_floor_document_job(v_job_no,'remnant_report','04-installation','quality_record','remnants_submitted',new.id::text,new.occurred_at);
    elsif new.event_type='cs_closed' then
      perform public.enqueue_floor_document_job(v_job_no,'handover','05-closing','quality_record','cs_closed',new.id::text,new.occurred_at);
    end if;
  exception when others then raise warning 'Closing document enqueue skipped for event %: %',new.id,sqlerrm; end;
  return new;
end $$;
revoke all on function public.track_floor_csat_and_closing_documents() from public,anon,authenticated;
drop trigger if exists trg_floor_docgen_closing_events on public.floor_work_order_events;
create trigger trg_floor_docgen_closing_events after insert on public.floor_work_order_events for each row execute function public.track_floor_csat_and_closing_documents();

create or replace function public.enqueue_floor_csat_document()
returns trigger language plpgsql security definer set search_path=public as $$
declare v_source timestamptz:=coalesce(new.updated_at,new.created_at,now());
begin
  if new.satisfaction_score is null then return new; end if;
  update public.floor_csat_followups set completed_at=now(),evaluation_id=new.id,updated_at=now() where job_no=new.job_no;
  perform public.enqueue_floor_document_job(new.job_no,'csat','05-closing','quality_record','csat_completed',new.id::text,v_source);
  return new;
exception when others then raise warning 'CSAT document enqueue skipped for evaluation %: %',new.id,sqlerrm; return new;
end $$;
revoke all on function public.enqueue_floor_csat_document() from public,anon,authenticated;
drop trigger if exists trg_floor_docgen_csat on public.job_evaluations;
create trigger trg_floor_docgen_csat after insert or update of satisfaction_score,answers,issues_text,needs_followup on public.job_evaluations for each row execute function public.enqueue_floor_csat_document();

