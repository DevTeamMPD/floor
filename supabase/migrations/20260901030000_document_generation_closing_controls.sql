-- Preserve the existing RPC name consumed by the UI, with evidence/NCR guard and audited exception.
create or replace function public.close_floor_work_order_cs_v3(p_work_order_id uuid)
returns boolean language plpgsql security definer set search_path=public as $$
declare v_order public.floor_work_orders%rowtype; v_actor public.floor_staff_profiles%rowtype; v_exception public.floor_close_exceptions%rowtype; v_missing text[]:=array[]::text[];
begin
  select * into v_actor from public.floor_staff_profiles where id=(select auth.uid()) and is_active and role in ('admin','cs');
  if v_actor.id is null then raise exception 'CS permission required'; end if;
  select * into v_order from public.floor_work_orders where id=p_work_order_id and status='waiting_cs' for update;
  if v_order.id is null then raise exception 'work order is not waiting for CS'; end if;
  if not exists(select 1 from public.floor_work_order_events where work_order_id=v_order.id and event_type='customer_signed') then v_missing:=array_append(v_missing,'customer_signature'); end if;
  if not exists(select 1 from public.floor_remnant_reports where job_no=v_order.job_no and status='accepted') then v_missing:=array_append(v_missing,'accepted_remnant_report'); end if;
  if not exists(select 1 from public.job_evaluations where job_no=v_order.job_no and satisfaction_score is not null) then v_missing:=array_append(v_missing,'csat'); end if;
  if exists(select 1 from public.ncr_reports where job_no=v_order.job_no and severity in ('critical','high') and status<>'closed') then v_missing:=array_append(v_missing,'open_high_ncr'); end if;
  if cardinality(v_missing)>0 then
    select * into v_exception from public.floor_close_exceptions where job_no=v_order.job_no and used_at is null order by approved_at desc limit 1 for update;
    if v_exception.id is null then raise exception 'closing requirements incomplete: %',array_to_string(v_missing,', '); end if;
    update public.floor_close_exceptions set used_at=now(),missing_requirements=to_jsonb(v_missing) where id=v_exception.id;
  end if;
  update public.floor_work_orders set status='closed',closed_at=now(),updated_at=now() where id=v_order.id;
  update public.install_jobs set stage=6,status='เสร็จสิ้น',waiting_on='ไม่ได้ค้าง',waiting_since=null,closed_at=coalesce(closed_at,now()),updated_at=now() where job_no=v_order.job_no;
  insert into public.floor_work_order_events(work_order_id,event_type,from_status,to_status,actor_staff_id,actor_name,note,metadata)
  values(v_order.id,'cs_closed','waiting_cs','closed',v_actor.id,v_actor.full_name,'CS ประเมินและปิดงาน',jsonb_build_object('exceptionId',v_exception.id,'missing',v_missing));
  return true;
end $$;
revoke all on function public.close_floor_work_order_cs_v3(uuid) from public,anon,authenticated;
grant execute on function public.close_floor_work_order_cs_v3(uuid) to authenticated;

